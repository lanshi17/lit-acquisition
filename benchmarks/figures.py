# ── Load data ──────────────────────────────────────────────────────────────
with open(RESULTS_DIR / "collected_results.json") as f:
    results = json.load(f)
with open(RESULTS_DIR / "derived_results.json") as f:
    results.update(json.load(f))  # adds full_pipeline_nested

with open(RESULTS_DIR / "metrics.json") as f:
    metrics = json.load(f)

with open(RESULTS_DIR / "paper_data.json") as f:
    paper_data = json.load(f)

GENE: dict[str, str] = {}
GOLD: dict[str, dict] = {}
with open(BENCH_DIR / "gold_standard" / "variants.jsonl") as f:
    for line in f:
        v = json.loads(line.strip())
        GENE[v["variant_id"]] = v["gene"]
        GOLD[v["variant_id"]] = v

NESTED = "full_pipeline_nested"
METHODS = ["pubmed_only", "multisource_no_translation", "multisource_with_translation", NESTED]
METHOD_TICKS = ["M1\nPubMed-only", "M2\nMulti-source", "M3\n+Translation", "M4\n+Cit.\\ graph"]

# Citation-graph semantic color, shared across figures.
CG_GREEN = "#55A868"


def per_variant(metric: str, k: str | None = None) -> dict[str, dict[str, float]]:
    """method -> {variant_id -> metric value} (new metrics.json schema)."""
    out: dict[str, dict[str, float]] = {m: {} for m in METHODS}
    for row in metrics:
        if row["method"] in out:
            val = row[metric] if k is None else row[metric][k]
            out[row["method"]][row["variant_id"]] = val
    return out


def stars(p: float) -> str:
    if p < 0.001:
        return "***"
    if p < 0.01:
        return "**"
    if p < 0.05:
        return "*"
    return "n.s."


# ── Figure 3a: Ablation (violin + box + per-variant points) ────────────────
def fig_ablation() -> None:
    rec = per_variant("set_recall")
    vids = sorted(rec["pubmed_only"])
    data = [np.array([rec[m][v] for v in vids]) for m in METHODS]
    pos = np.arange(1, len(METHODS) + 1)

    fig, ax = plt.subplots(figsize=(3.4, 2.9))

    # Violin bodies: sequential Blues to convey the cumulative ablation chain.
    blues = ["#C6DBEF", "#9ECAE1", "#6BAED6", "#3182BD"]
    parts = ax.violinplot(data, positions=pos, widths=0.78, showextrema=False)
    for body, color in zip(parts["bodies"], blues):
        body.set_facecolor(color)
        body.set_edgecolor("#31608F")
        body.set_linewidth(0.5)
        body.set_alpha(0.75)

    # Narrow inner boxplot: median + IQR + 1.5*IQR whiskers.
    ax.boxplot(
        data, positions=pos, widths=0.13, showfliers=False, patch_artist=True,
        boxprops=dict(facecolor="white", edgecolor="black", linewidth=0.6),
        medianprops=dict(color="black", linewidth=0.9),
        whiskerprops=dict(color="black", linewidth=0.6),
        capprops=dict(color="black", linewidth=0.6),
    )

    # Jittered per-variant points (n=30 per method), reproducible seed.
    rng = np.random.default_rng(42)
    for x0, d in zip(pos, data):
        x = x0 + rng.uniform(-0.10, 0.10, size=len(d))
        ax.scatter(x, d, s=4.5, color="#3A3A3A", alpha=0.6, linewidths=0, zorder=4)

    # Mean markers.
    ax.scatter(pos, [d.mean() for d in data], marker="D", s=15,
               facecolor="white", edgecolor="black", linewidth=0.7, zorder=5)

    # Paired Wilcoxon brackets with HOLM-CORRECTED p-values (paper_data.json).
    T = paper_data["tests_holm"]
    brackets = [
        (1, 2, T["M2_vs_M1_set_recall"]["p_holm"], 0.80),
        (2, 3, T["M3_vs_M2_set_recall"]["p_holm"], 0.66),
        (3, 4, T["M4n_vs_M3_set_recall"]["p_holm"], 0.66),
        (1, 4, T["M4n_vs_M1_set_recall"]["p_holm"], 0.90),
    ]
    for x1, x2, p, y in brackets:
        xa, xb, dy = x1 + 0.06, x2 - 0.06, 0.012
        ax.plot([xa, xa, xb, xb], [y, y + dy, y + dy, y], ls="-", lw=0.7, color="black")
        ax.text((xa + xb) / 2, y + dy + 0.004, stars(p), ha="center", va="bottom", fontsize=7)

    ax.set_xticks(pos)
    ax.set_xticklabels(METHOD_TICKS)
    ax.set_ylabel("Set recall (all retrieved candidates)")
    ax.set_xlim(0.45, len(METHODS) + 0.55)
    ax.set_ylim(-0.02, 0.99)
    fig.tight_layout()
    fig.savefig(FIG_DIR / "fig3_ablation.png", dpi=300)
    fig.savefig(FIG_DIR / "fig3_ablation.pdf")
    plt.close(fig)
    print("✓ fig3_ablation.png")


# ── Figure 5: Per-variant paired scatter (M1 vs nested M4) ─────────────────
def fig_pervariant_scatter() -> None:
    rec = per_variant("set_recall")
    m1, m4 = rec["pubmed_only"], rec[NESTED]
    rel_total = {r["variant_id"]: r["n_relevant"] for r in metrics if r["method"] == NESTED}
    cg_relevant = {r["variant_id"]: r["source_coverage"].get("citation_graph", 0)
                   for r in metrics if r["method"] == NESTED}
    vids = sorted(m1)

    up = sum(1 for v in vids if m4[v] - m1[v] > 1e-9)
    down = sum(1 for v in vids if m1[v] - m4[v] > 1e-9)
    print(f"  paired M1->M4n: improved {up}, tied {len(vids) - up - down}, regressed {down}")

    lo, hi = -0.03, 0.83
    fig, ax = plt.subplots(figsize=(3.4, 3.4))

    # Improvement region and identity line.
    ax.fill_between([lo, hi], [lo, hi], [hi, hi], color="#4C72B0", alpha=0.06, lw=0, zorder=0)
    ax.plot([lo, hi], [lo, hi], ls="--", lw=0.8, color="#888888", zorder=1)
    ax.text(0.655, 0.685, "$y=x$", fontsize=7, color="#666666", ha="right", va="bottom", rotation=45)

    for vid in vids:
        x, y = m1[vid], m4[vid]
        if cg_relevant[vid] > 0:
            color = CG_GREEN
        elif y - x > 1e-9:
            color = "#4C72B0"
        else:
            color = "#B0B0B0"
        # Marker area encodes the variant's gold-set size (4-32 papers).
        ax.scatter(x, y, s=4 + 2.0 * rel_total[vid], facecolor=color, alpha=0.85,
                   edgecolor="#333333", linewidths=0.5, zorder=3)

    # Annotate variants discussed in the paper (V011/V013 coincide exactly).
    notes = {
        "V030": ("DMPK", (0.085, 0.605)),
        "V012": ("EGFR", (0.125, 0.537)),
        "V011": ("KRAS, BRAF", (0.018, 0.496)),
        "V027": ("DMD", (0.025, 0.380)),
        "V022": ("PAH", (0.170, 0.428)),
        "V014": ("APC", (0.025, 0.105)),
        "V009": ("MYH7", (0.700, 0.268)),
    }
    for vid, (label, xytext) in notes.items():
        ax.annotate(label, xy=(m1[vid], m4[vid]), xytext=xytext, fontsize=7,
                    color="#333333",
                    arrowprops=dict(arrowstyle="-", lw=0.5, color="#999999",
                                    shrinkA=1, shrinkB=2))

    handles = [
        Line2D([], [], marker="o", ls="", mfc=CG_GREEN, mec="#333333", mew=0.5,
               ms=5, label="citation-graph gain"),
        Line2D([], [], marker="o", ls="", mfc="#4C72B0", mec="#333333", mew=0.5,
               ms=5, label="improved"),
        Line2D([], [], marker="o", ls="", mfc="#B0B0B0", mec="#333333", mew=0.5,
               ms=5, label="tied / regressed"),
    ]
    ax.legend(handles=handles, loc="lower right", frameon=False, handletextpad=0.2)

    ax.set_xlabel("Set recall, M1 (PubMed-only)")
    ax.set_ylabel("Set recall, M4 (nested full pipeline)")
    ax.set_xlim(lo, hi)
    ax.set_ylim(lo, hi)
    ax.set_xticks(np.arange(0, 0.81, 0.2))
    ax.set_yticks(np.arange(0, 0.81, 0.2))
    ax.set_aspect("equal")
    fig.tight_layout()
    fig.savefig(FIG_DIR / "fig5_pervariant_scatter.png", dpi=300)
    fig.savefig(FIG_DIR / "fig5_pervariant_scatter.pdf")
    plt.close(fig)
    print("✓ fig5_pervariant_scatter.png")


# ── Figure 2: Source coverage (first-seen attribution) ─────────────────────
def fig_source_coverage() -> None:
    # Unique retrieved papers (by DOI) per first-seen source, nested pipeline.
    unique = defaultdict(set)
    for vid, papers in results[NESTED].items():
        for p in papers:
            doi = (p.get("doi") or "").lower().strip()
            if doi:
                unique[p.get("source", "?")].add(doi)
    # Gold-standard-relevant papers per source (first-seen attribution).
    relevant = Counter()
    for r in metrics:
        if r["method"] == NESTED:
            relevant.update(r["source_coverage"])

    sources = ["crossref", "pmc", "citation_graph", "europepmc"]
    labels = ["Crossref", "PMC", "Citation\ngraph", "EuropePMC"]
    ret = [len(unique.get(s, set())) for s in sources]
    rel = [relevant.get(s, 0) for s in sources]
    print(f"  source coverage: retrieved {ret}, relevant {rel}")

    x = np.arange(len(sources))
    w = 0.38
    fig, ax = plt.subplots(figsize=(3.4, 2.4))
    ax.bar(x - w / 2, ret, w, label="Retrieved (unique DOIs)", color="#C9C9C9",
           edgecolor="black", linewidth=0.4)
    ax.bar(x + w / 2, rel, w, label="Relevant (reference set)", color="#4C72B0",
           edgecolor="black", linewidth=0.4)
    for xi, (a, b) in zip(x, zip(ret, rel)):
        ax.text(xi - w / 2, a + 5, str(a), ha="center", va="bottom", fontsize=7)
        ax.text(xi + w / 2, b + 5, str(b), ha="center", va="bottom", fontsize=7)
    ax.set_xticks(x)
    ax.set_xticklabels(labels)
    ax.set_ylabel("Papers (nested pipeline)")
    ax.set_ylim(0, max(ret) * 1.22)
    ax.legend(loc="upper right", frameon=False)
    fig.tight_layout()
    fig.savefig(FIG_DIR / "fig2_source_coverage.png", dpi=300)
    fig.savefig(FIG_DIR / "fig2_source_coverage.pdf")
    plt.close(fig)
    print("✓ fig2_source_coverage.png")


# ── Figure 3b: Multilingual (gold de/fr recovery; M2 vs M3 isolates it) ────
def fig_multilingual() -> None:
    lang = paper_data["language_analysis"]
    gold_totals = lang["gold_totals"]
    found = lang["found_by_method"]

    langs = ["de", "fr"]
    lang_labels = [f"German\n({gold_totals['de']} annotated)",
                   f"French\n({gold_totals['fr']} annotated)"]
    methods = ["pubmed_only", "multisource_no_translation", "multisource_with_translation"]
    method_labels = ["M1 PubMed-only", "M2 Multi-source", "M3 +Translation"]
    colors = ["#C9C9C9", "#9ECAE1", "#3182BD"]

    x = np.arange(len(langs))
    w = 0.26
    fig, ax = plt.subplots(figsize=(3.4, 2.4))
    for i, (m, label, color) in enumerate(zip(methods, method_labels, colors)):
        vals = [found[m].get(l, 0) for l in langs]
        bars = ax.bar(x + (i - 1) * w, vals, w, label=label, color=color,
                      edgecolor="black", linewidth=0.4)
        for xi, v in zip(x + (i - 1) * w, vals):
            ax.text(xi, v + 0.25, str(v), ha="center", va="bottom", fontsize=7)

    # Annotated gold totals as reference caps.
    for xi, l in zip(x, langs):
        ax.hlines(gold_totals[l], xi - 1.65 * w, xi + 1.65 * w,
                  colors="#888888", linestyles=":", linewidth=0.8)
    ax.text(x[-1] + 1.7 * w, gold_totals[langs[-1]] + 0.3, "annotated total",
            fontsize=6.5, color="#666666", ha="right", va="bottom")

    print(f"  multilingual: " + ", ".join(
        f"{m}: de={found[m].get('de',0)} fr={found[m].get('fr',0)}" for m in methods))

    ax.set_xticks(x)
    ax.set_xticklabels(lang_labels)
    ax.set_ylabel("Annotated non-English papers found")
    ax.set_ylim(0, 15.5)
    ax.legend(loc="upper center", frameon=False, ncol=3, fontsize=6.5,
              bbox_to_anchor=(0.5, 1.14), handlelength=1.2, columnspacing=0.9)
    fig.tight_layout()
    fig.savefig(FIG_DIR / "fig3_multilingual.png", dpi=300)
    fig.savefig(FIG_DIR / "fig3_multilingual.pdf")
    plt.close(fig)
    print("✓ fig3_multilingual.png")


# ── Figure 4: Citation graph retrieved vs relevant per gene ────────────────
def fig_citation_graph() -> None:
    retrieved = {}
    for vid, papers in results[NESTED].items():
        n = sum(1 for p in papers if p.get("source") == "citation_graph")
        if n:
            retrieved[vid] = n
    relevant = {r["variant_id"]: r["source_coverage"].get("citation_graph", 0)
                for r in metrics if r["method"] == NESTED}
    print(f"  citation graph: retrieved {sum(retrieved.values())}, "
          f"relevant {sum(relevant.values())}")

    # Ascending sort so the highest-relevance genes end up at the top of barh.
    order = sorted(retrieved, key=lambda v: (relevant.get(v, 0), retrieved[v]))
    genes = [GENE[v] for v in order]
    ret = [retrieved[v] for v in order]
    rel = [relevant.get(v, 0) for v in order]

    y = np.arange(len(order))
    h = 0.38
    fig, ax = plt.subplots(figsize=(3.4, 3.2))
    ax.barh(y + h / 2, ret, h, label="Retrieved", color="#C9C9C9",
            edgecolor="black", linewidth=0.4)
    ax.barh(y - h / 2, rel, h, label="Relevant (reference set)", color=CG_GREEN,
            edgecolor="black", linewidth=0.4)
    for yi, r in zip(y, rel):
        if r:
            ax.text(r + 0.35, yi - h / 2, str(r), va="center", fontsize=7)
    # Traversal paper budget (20 per variant).
    ax.axvline(20, ls=":", lw=0.7, color="#888888")

    ax.set_yticks(y)
    ax.set_yticklabels(genes)
    ax.set_ylim(-0.7, len(order) - 0.3)
    ax.set_xlim(0, 22)
    ax.set_xlabel("Citation-graph papers (nested pipeline)")
    ax.legend(loc="lower right", frameon=False)
    fig.tight_layout()
    fig.savefig(FIG_DIR / "fig4_citation_graph.png", dpi=300)
    fig.savefig(FIG_DIR / "fig4_citation_graph.pdf")
    plt.close(fig)
    print("✓ fig4_citation_graph.png")


# ── Figure 6: Recall@K sweep with bootstrap CI bands ───────────────────────
def fig_recall_at_k(k_max: int = 50, n_boot: int = 10_000) -> None:
    vids = sorted(GOLD)
    ks = np.arange(1, k_max + 1)

    # R[method] is a (variants x K) matrix of Recall@K values.
    R = {
        m: np.array([[compute_recall_at_k(results[m][v], GOLD[v]["relevant_papers"], int(k))
                      for k in ks] for v in vids])
        for m in METHODS
    }

    rng = np.random.default_rng(42)
    idx = rng.integers(0, len(vids), size=(n_boot, len(vids)))

    labels = ["M1 PubMed-only", "M2 Multi-source", "M3 +Translation", "M4 +Cit.\\ graph (nested)"]
    colors = ["#9ECAE1", "#6BAED6", "#3182BD", "#08519C"]
    styles = [":", "-.", "--", "-"]
    markers = ["o", "s", "^", "D"]

    fig, ax = plt.subplots(figsize=(3.4, 2.5))
    for m, label, color, ls, marker in zip(METHODS, labels, colors, styles, markers):
        mean = R[m].mean(axis=0)
        boot_means = R[m][idx].mean(axis=1)  # (n_boot, K)
        lo, hi = np.percentile(boot_means, [2.5, 97.5], axis=0)
        ax.fill_between(ks, lo, hi, color=color, alpha=0.13, lw=0)
        ax.plot(ks, mean, ls=ls, lw=1.0, color=color, marker=marker, ms=2.4,
                markevery=5, markerfacecolor=color, markeredgecolor="black",
                markeredgewidth=0.3, label=label)
        print(f"  recall@K {m}: @10={mean[9]:.3f} @20={mean[19]:.3f} @50={mean[49]:.3f}")

    ax.set_xlabel("$K$")
    ax.set_ylabel("Recall@$K$")
    ax.set_xlim(1, k_max)
    ax.set_ylim(0, 0.44)
    ax.legend(loc="upper left", frameon=False, handlelength=2.2)
    fig.tight_layout()
    fig.savefig(FIG_DIR / "fig6_recall_at_k.png", dpi=300)
    fig.savefig(FIG_DIR / "fig6_recall_at_k.pdf")
    plt.close(fig)
    print("✓ fig6_recall_at_k.png")


# ── Figure 7: Per-variant component contribution heatmap ───────────────────
def fig_component_heatmap() -> None:
    rec = per_variant("set_recall")
    vids = sorted(rec["pubmed_only"])
    m1 = np.array([rec["pubmed_only"][v] for v in vids])
    m2 = np.array([rec["multisource_no_translation"][v] for v in vids])
    m3 = np.array([rec["multisource_with_translation"][v] for v in vids])
    m4 = np.array([rec[NESTED][v] for v in vids])

    deltas = np.vstack([m2 - m1, m3 - m2, m4 - m3])
    order = np.argsort(-(m4 - m1))  # sort variants by total gain, descending
    deltas = deltas[:, order]
    genes = [GENE[vids[i]] for i in order]
    vmax = 0.75

    fig, ax = plt.subplots(figsize=(7.0, 1.75))
    mesh = ax.pcolormesh(deltas, cmap="RdBu", vmin=-vmax, vmax=vmax,
                         edgecolors="white", linewidth=0.4)
    ax.set_xticks(np.arange(len(genes)) + 0.5)
    ax.set_xticklabels(genes, rotation=90, fontsize=6)
    ax.set_yticks(np.arange(3) + 0.5)
    ax.set_yticklabels(["Multi-source", "+Translation", "+Cit.\\ graph"], fontsize=7.5)
    ax.invert_yaxis()  # first component on top
    ax.tick_params(length=0)
    cbar = fig.colorbar(mesh, ax=ax, fraction=0.03, pad=0.012)
    cbar.set_label(r"$\Delta$ set recall", fontsize=7.5)
    cbar.ax.tick_params(labelsize=6.5)
    fig.tight_layout()
    fig.savefig(FIG_DIR / "fig7_component_heatmap.png", dpi=300)
    fig.savefig(FIG_DIR / "fig7_component_heatmap.pdf")
    plt.close(fig)
    print("✓ fig7_component_heatmap.png")


