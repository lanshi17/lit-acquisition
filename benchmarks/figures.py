"""Generate publication-quality figures for the JCDL paper.

Outputs to benchmarks/paper_figures/ (all sized for one ACM column):
  fig2_source_coverage.png/.pdf     — first-seen source attribution
  fig3_ablation.png/.pdf            — per-variant set-recall distributions
                                      (violin + box + points) with paired
                                      Wilcoxon brackets (Holm-corrected)
  fig3_multilingual.png/.pdf        — gold de/fr recovery per method
                                      (M2 vs M3 isolates translation)
  fig4_citation_graph.png/.pdf      — citation graph: retrieved vs. relevant
                                      papers per gene
  fig5_pervariant_scatter.png/.pdf  — paired per-variant set-recall scatter,
                                      M1 (PubMed-only) vs. M4 (nested)
  fig6_recall_at_k.png/.pdf         — mean Recall@K sweep (K=1..50) with
                                      bootstrap 95% CI bands
  fig7_component_heatmap.png/.pdf   — per-variant recall delta of each
                                      ablation component (diverging heatmap)

The ablation methods are M1-M3 plus the STRICTLY NESTED M4 (frozen M3 list
+ recorded citation-graph candidates), so component deltas are not
confounded by live-API re-retrieval variance. All statistics are read from
results/paper_data.json (regenerated by make_paper_data.py) so figure
annotations match the paper tables exactly.

Figures use the scienceplots 'science'/'ieee' styles with LaTeX text
rendering (text.usetex); requires latex + dvipng (Debian TeX Live).
"""

