def load(name: str) -> dict[str, Any] | None:
    path = RESULTS / name
    if not path.exists():
        return None
    return json.loads(path.read_text())


def esc(text: str) -> str:
    """Minimal LaTeX escaping for artifact strings."""
    for old, new in (("&", r"\&"), ("%", r"\%"), ("_", r"\_"), ("#", r"\#"), ("$", r"\$")):
        text = text.replace(old, new)
    return text


def sig(test: dict[str, Any]) -> str:
    return "yes" if test.get("significant_holm") else "no"


def p_holm(test: dict[str, Any]) -> str:
    value = test.get("p_holm")
    if value is None:
        return "n/a"
    if value < 1e-4:
        return r"$<10^{-4}$"
    if value < 0.001:
        mantissa, exponent = f"{value:.1e}".split("e")
        return rf"${mantissa}\times10^{{{int(exponent)}}}$"
    return f"{value:.3f}"


